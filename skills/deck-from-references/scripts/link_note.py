#!/usr/bin/env python3
"""Link deck pages to the detailed reading note they come from.

  link_note.py build NOTE.aux --pdf NOTE.pdf [--lang ja|en] --out note_links.tex
  link_note.py check DECK.tex [DECK2.tex ...] --aux NOTE.aux
  link_note.py reverse DECK.tex [...] --aux NOTE.aux --out deck_map.tex [--lang ja|en]

`build` reads the note's .aux (\\newlabel entries) and writes data for notelink.sty: each label
with its printed number and PDF page, so a deck page can say "detailed note §11.4, p.89" with a
link, and the page numbers follow the note's last build.
`check` splits the deck sources into frames (title frames [plain] are skipped) and reports a
frame with neither \\noteref{labels} nor \\nonote{reason}, and a label missing from the .aux.
`reverse` writes a TeX list for the note's appendix: for each note label, the deck pages that
use it (the page is the number at the start of \\frametitle, "12. Title").
Exit status 1 when `check` finds a problem.
"""
import argparse, re, sys

PREFIX = {'ja': {'sec': '§{}', 'def': '§{}', 'eq': '式({})', 'fig': '図{}', 'df': '定義{}'},
          'en': {'sec': '§{}', 'def': '§{}', 'eq': 'Eq.({})', 'fig': 'Fig.{}', 'df': 'Def.{}'}}


def read_aux(path):
    labels = {}
    for line in open(path, encoding='utf-8', errors='replace'):
        m = re.match(r'\\newlabel\{([^}]+)\}\{\{([^}]*)\}\{([^}]*)\}', line)
        if not m:
            continue
        key, num, page = m.groups()
        if '@' in key or not num or not page.isdigit():
            continue
        labels[key] = (num, int(page))
    return labels


def printed(key, num, lang):
    if not re.fullmatch(r'[0-9A-Za-z.]+', num):   # a named target (e.g. an unnumbered Bibliography)
        return num
    kind = key.split(':', 1)[0]
    fmt = PREFIX[lang].get(kind, '{}')
    return fmt.format(num)


def frames(text):
    out = []
    for m in re.finditer(r'\\begin\{frame\}(\[[^\]]*\])?(.*?)\\end\{frame\}', text, re.S):
        opts, body = m.group(1) or '', m.group(2)
        if 'plain' in opts:
            continue
        t = re.search(r'\\frametitle\{(\d+)\.', body)
        out.append((int(t.group(1)) if t else None, body))
    return out


def keys_in(body):
    ks = []
    for m in re.finditer(r'\\noteref\{([^}]*)\}', body):
        ks += [k.strip() for k in m.group(1).split(',') if k.strip()]
    return ks


def cmd_build(a):
    labels = read_aux(a.aux)
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write('%% generated by link_note.py from %s; do not edit\n' % a.aux)
        f.write('\\renewcommand{\\NotePDF}{%s}\n' % a.pdf)
        for k in sorted(labels):
            num, page = labels[k]
            f.write('\\notedef{%s}{%s}{%d}\n' % (k, printed(k, num, a.lang).replace('§', '\\S{}'), page))
    print(f'{len(labels)} labels -> {a.out}')


def cmd_check(a):
    labels = read_aux(a.aux)
    bad = 0
    n = 0
    for path in a.deck:
        for no, body in frames(open(path, encoding='utf-8').read()):
            n += 1
            ks = keys_in(body)
            tag = f'{path} page {no if no is not None else "?"}'
            if not ks and '\\nonote{' not in body:
                print(f'{tag}: no \\noteref and no \\nonote'); bad += 1
            for k in ks:
                if k not in labels:
                    print(f'{tag}: label {k!r} not in the note .aux'); bad += 1
    print(f'{n} pages checked, {bad} problem(s)')
    sys.exit(1 if bad else 0)


def cmd_reverse(a):
    labels = read_aux(a.aux)
    use = {}
    for path in a.deck:
        for no, body in frames(open(path, encoding='utf-8').read()):
            for k in keys_in(body):
                use.setdefault(k, []).append(no)
    head = {'ja': ('デッキとの対応', '詳細版の節・式・図が、理解用デッキのどの頁（R番号）で使われるか。'),
            'en': ('Correspondence with the deck', 'For each section, equation or figure of this note, the deck pages (R numbers) that use it.')}[a.lang]
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write('% generated by link_note.py reverse; do not edit\n')
        f.write('\\section*{%s}\\addcontentsline{toc}{section}{%s}\n%s\n\\begin{itemize}\\small\n' % (head[0], head[0], head[1]))
        for k in sorted(use, key=lambda k: (labels.get(k, ('', 0))[1], k)):
            num, page = labels.get(k, ('?', 0))
            pages = ', '.join('R%s' % p for p in sorted(set(x for x in use[k] if x is not None)))
            f.write('\\item %s\\ (p.\\,%d)\\ \\texttt{%s}: %s\n' % (printed(k, num, a.lang).replace('§', '\\S{}'), page, k.replace('_', '\\_'), pages))
        f.write('\\end{itemize}\n')
    print(f'{len(use)} labels used -> {a.out}')


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest='cmd', required=True)
    b = sub.add_parser('build'); b.add_argument('aux'); b.add_argument('--pdf', required=True)
    b.add_argument('--lang', default='ja', choices=PREFIX); b.add_argument('--out', required=True)
    c = sub.add_parser('check'); c.add_argument('deck', nargs='+'); c.add_argument('--aux', required=True)
    r = sub.add_parser('reverse'); r.add_argument('deck', nargs='+'); r.add_argument('--aux', required=True)
    r.add_argument('--lang', default='ja', choices=PREFIX); r.add_argument('--out', required=True)
    a = ap.parse_args()
    {'build': cmd_build, 'check': cmd_check, 'reverse': cmd_reverse}[a.cmd](a)


if __name__ == '__main__':
    main()
